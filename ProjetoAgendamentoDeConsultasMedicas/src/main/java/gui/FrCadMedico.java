    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        this.nomeAntigo = JOptionPane.showInputDialog("informe o nome do medico.");
         
         medico Medico = this.gerente.buscar(nomeAntigo);
         if(Medico == null){
               JOptionPane.showMessageDialog(this, "Medico inexistente");
         }else{
             this.gerente.Remover(nomeAntigo);
               JOptionPane.showMessageDialog(this, "Exclusao feita com sucesso!");
         }
         String Listagem = this.gerente.toString();
         edtListagem.setText(Listagem);
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
         medico novoMedico = this.camposParaObjeto();
    if(this.editando == true)
         this.gerente.atualizar(this.nomeAntigo, novoMedico);
     else     
     this.gerente.adicionar(novoMedico);
     this.LimparCampos();
     this.HabilitarCampos(false);
     this.editando = false;
     
     String Listagem = gerente.toString();
     edtListagem.setText(Listagem);
     
       try {
           gerente.salvarNoArquivo("ListaMedicos.json");
       } catch (IOException ex) {
           Logger.getLogger(FrCadMedico.class.getName()).log(Level.SEVERE, null, ex);
       }
    }//GEN-LAST:event_btnSalvarActionPerformed

    public void objetoParaCampos(medico Medico){
         edtCrm.setText(Medico.getCRM());
         edtEspecialidade.setText(Medico.getEspecialidade());
         edtNome.setText(Medico.getNome());
         edtHorarioDisponivel.setText(Medico.getHorariodisponivel());
     }
     
      public medico camposParaObjeto(){
         medico m = new medico();
         m.setCRM(edtCrm.getText().trim());
         m.setNome(edtNome.getText().trim());
         m.setEspecialidade(edtEspecialidade.getText().trim());
         m.setHorariodisponivel(edtHorarioDisponivel.getText().trim());
      return m;   
     }
    
    
    public void HabilitarCampos(boolean flag){
         edtEspecialidade.setEnabled(flag);
         edtCrm.setEnabled(flag);
         edtNome.setEnabled(flag);
         edtHorarioDisponivel.setEnabled(flag);
     }
     
     public void LimparCampos(){
         edtEspecialidade.setText(" ");
         edtCrm.setText(" ");
         edtNome.setText(" ");
         edtHorarioDisponivel.setText(" ");
     }
    

