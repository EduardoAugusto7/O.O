    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
 this.nomeAntigo = JOptionPane.showInputDialog("informe o nome do medico.");
      medico medicoEditando = this.gerente.buscar(nomeAntigo);
      
      if(medicoEditando != null){
          this.editando = true;
          this.LimparCampos();
          this.HabilitarCampos(true);
          this.objetoParaCampos(medicoEditando);
          
      }else{
          System.out.println("Medico inexistente.");
          JOptionPane.showMessageDialog(this, "Medico inexistente");
      } 
    }//GEN-LAST:event_btnEditarActionPerformed

