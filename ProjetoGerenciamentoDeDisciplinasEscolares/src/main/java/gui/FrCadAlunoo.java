    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        this.nomeAntigo = JOptionPane.showInputDialog("informe o nome do aluno.");
         
         Alunos aluno = this.gerente.buscar(nomeAntigo);
         if(aluno == null){
               JOptionPane.showMessageDialog(this, "Aluno inexistente");
         }else{
             this.gerente.remover(nomeAntigo);
               JOptionPane.showMessageDialog(this, "Exclusao feita com sucesso!");
         }
         String Listagem = this.gerente.toString();
         edtListagem.setText(Listagem);
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
    Alunos novoAluno = this.camposParaObjeto();
    if(this.editando == true)
         this.gerente.atualizarAlunos(this.nomeAntigo, novoAluno);
     else     
     this.gerente.adicionar(novoAluno);
     this.LimparCampos();
     this.HabilitarCampos(false);
     this.editando = false;
     
     String Listagem = gerente.toString();
     edtListagem.setText(Listagem);
     
       try {
           gerente.salvarNoArquivo("ListaAlunos.json");
       } catch (IOException ex) {
           Logger.getLogger(FrCadAluno.class.getName()).log(Level.SEVERE, null, ex);
       }
    }//GEN-LAST:event_btnSalvarActionPerformed

    public void objetoParaCampos(Alunos alunos){
         edtCpf.setText(alunos.getCpf());
         edtIdade.setText(alunos.getIdade()+ " ");
         edtNome.setText(alunos.getNome());
         edtSexo.setText(alunos.getSexo());
     }
     
      public Alunos camposParaObjeto(){
         Alunos a = new Alunos();
         a.setCpf(edtCpf.getText().trim());
         a.setNome(edtNome.getText().trim());
         a.setSexo(edtSexo.getText().trim());
         
         String idadeStr = edtIdade.getText().trim();
         if(!idadeStr.isEmpty()){
         int idade = Integer.parseInt(idadeStr);
         a.setIdade(idade);
         }
         
      return a;   
     }
    
    
    public void HabilitarCampos(boolean flag){
         edtCpf.setEnabled(flag);
         edtIdade.setEnabled(flag);
         edtNome.setEnabled(flag);
         edtSexo.setEnabled(flag);
     }
     
     public void LimparCampos(){
         edtCpf.setText(" ");
         edtIdade.setText(" ");
         edtNome.setText(" ");
         edtSexo.setText(" ");
     }


