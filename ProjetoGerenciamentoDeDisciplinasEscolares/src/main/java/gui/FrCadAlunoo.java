    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
         this.nomeAntigo = JOptionPane.showInputDialog("informe o nome do aluno.");
      Alunos alunoEditando = this.gerente.buscar(nomeAntigo);
      
      if(alunoEditando != null){
          this.editando = true;
          this.LimparCampos();
          this.HabilitarCampos(true);
          this.objetoParaCampos(alunoEditando);
          
      }else{
          System.out.println("Aluno inexistente.");
          JOptionPane.showMessageDialog(this, "Aluno inexistente");
      } 
    }//GEN-LAST:event_btnEditarActionPerformed

