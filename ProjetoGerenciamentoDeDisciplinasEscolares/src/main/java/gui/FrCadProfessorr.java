    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
         this.nomeAntigo = JOptionPane.showInputDialog("informe o nome do professor.");
      Professor professorEditando = this.gerente.buscar(nomeAntigo);
      
      if(professorEditando != null){
          this.editando = true;
          this.LimparCampos();
          this.HabilitarCampos(true);
          this.objetoParaCampos(professorEditando);
          
      }else{
          System.out.println("Professor inexistente.");
          JOptionPane.showMessageDialog(this, "Professor inexistente");
      } 
    }//GEN-LAST:event_btnEditarActionPerformed

