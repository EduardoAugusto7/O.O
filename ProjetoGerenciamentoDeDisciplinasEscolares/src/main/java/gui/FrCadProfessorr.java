    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
       this.nomeAntigo = JOptionPane.showInputDialog("informe o nome do professor.");
         
         Professor professor = this.gerente.buscar(nomeAntigo);
         if(professor == null){
               JOptionPane.showMessageDialog(this, "Professor inexistente");
         }else{
             this.gerente.remover(nomeAntigo);
               JOptionPane.showMessageDialog(this, "Exclusao feita com sucesso!");
         }
         String Listagem = this.gerente.toString();
         edtListagem.setText(Listagem);
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        Professor novoProfessor = this.camposParaObjeto();
    if(this.editando == true)
         this.gerente.atualizarProfessores(this.nomeAntigo, novoProfessor);
     else     
     this.gerente.adicionar(novoProfessor);
     this.LimparCampos();
     this.HabilitarCampos(false);
     this.editando = false;
     
     String Listagem = gerente.toString();
     edtListagem.setText(Listagem);
     
       try {
           gerente.salvarNoArquivo("ListaProfessores.json");
       } catch (IOException ex) {
           Logger.getLogger(FrCadProfessor.class.getName()).log(Level.SEVERE, null, ex);
       }
    }//GEN-LAST:event_btnSalvarActionPerformed

    public void objetoParaCampos(Professor professores){
         edtCpf.setText(professores.getCpf());
         edtIdade.setText(professores.getIdade()+ " ");
         edtNome.setText(professores.getNome());
         edtSexo.setText(professores.getSexo());
     }
     
      public Professor camposParaObjeto(){
         Professor p = new Professor();
         p.setCpf(edtCpf.getText().trim());
         p.setNome(edtNome.getText().trim());
         p.setSexo(edtSexo.getText().trim());
         
         String idadeStr = edtIdade.getText().trim();
         if(!idadeStr.isEmpty()){
         int idade = Integer.parseInt(idadeStr);
         p.setIdade(idade);
         }
         
      return p;   
     }
    
    
    public void HabilitarCampos(boolean flag){
         edtCpf.setEnabled(flag);
         edtIdade.setEnabled(flag);
         edtNome.setEnabled(flag);
         edtSexo.setEnabled(flag);
     }
     
     public void LimparCampos(){
         edtCpf.setText(" ");
         edtIdade.setText(" ");
         edtNome.setText(" ");
         edtSexo.setText(" ");
     }


